def normalize(raw) -> str:
    """Привести код к виду 0300-4006 или 0300-0200-0001-0001."""
    if raw is None:
        return ""
    if isinstance(raw, (int, float)):
        value = f"{int(raw):08X}"
    else:
        value = str(raw).strip().upper()
    value = value.replace("HMS_", "").replace("_", "").replace("-", "").replace(" ", "")
    if not value or not all(c in "0123456789ABCDEF" for c in value):
        return str(raw).strip().upper()
    if len(value) <= 8:
        value = value.rjust(8, "0")
        return f"{value[:4]}-{value[4:8]}"
    value = value.rjust(16, "0")
    return f"{value[:4]}-{value[4:8]}-{value[8:12]}-{value[12:16]}"


def hms_code(item) -> str:
    """Собрать код из пары attr/code, как их присылает принтер."""
    if isinstance(item, dict):
        attr = item.get("attr")
        code = item.get("code")
        if attr is not None and code is not None:
            try:
                attr_i, code_i = int(attr), int(code)
            except (TypeError, ValueError):
                return normalize(code if code is not None else attr)
            return (f"{attr_i >> 16:04X}-{attr_i & 0xFFFF:04X}"
                    f"-{code_i >> 16:04X}-{code_i & 0xFFFF:04X}")
        return normalize(code if code is not None else attr)
    return normalize(item)


def decode(raw) -> dict:
    """Понятное описание кода: заголовок, причина, совет, важность."""
    code = raw if isinstance(raw, str) and "-" in raw else hms_code(raw)
    entry = CODES.get(code)
    if not entry:
        # Пробуем укороченный вид: 0300-4006 внутри длинного кода.
        parts = code.split("-")
        if len(parts) == 4:
            entry = CODES.get(f"{parts[0]}-{parts[1]}")
        if not entry and parts:
            entry = CODES.get(parts[0])
    if entry:
        title, reason, advice, severity, blocking = entry
        known = True
    else:
        group = code.split("-")[0] if code else ""
        name, hint = SUBSYSTEMS.get(group, ("Неизвестный узел", "Подсистема не распознана."))
        title = f"{name}: код {code}" if code else "Неизвестная ошибка"
        reason = hint
        advice = ("Полное описание — на wiki.bambulab.com по этому коду. "
                  "Если печать остановилась, проверьте деталь перед перезапуском.")
        severity, blocking, known = "warn", False, False
    return {
        "code": code,
        "title": title,
        "reason": reason,
        "advice": advice,
        "severity": severity,
        "severity_label": SEVERITY_LABEL.get(severity, severity),
        "blocking": blocking,
        "known": known,
        "wiki": f"https://wiki.bambulab.com/en/x1/troubleshooting/how-to-solve-{code.lower()}"
                if code else "",
    }


def decode_list(items) -> list[dict]:
    """Расшифровать список hms из снимка принтера."""
    result, seen = [], set()
    for item in items or []:
        info = decode(item)
        if info["code"] in seen:
            continue
        seen.add(info["code"])
        result.append(info)
    return result


def worst(items: list[dict]) -> str:
    """Максимальный уровень важности среди расшифрованных кодов."""
    order = ["info", "warn", "error", "fatal"]
    level = ""
    for item in items:
        if not level or order.index(item["severity"]) > order.index(level):
            level = item["severity"]
    return level
