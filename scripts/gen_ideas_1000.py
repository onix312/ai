def combos(subjects: list[str], actions: list[str], count: int = 19) -> list[str]:
    out: list[str] = []
    for s in subjects:
        for a in actions:
            out.append(f"{s} — {a}")
    # 5×4 = 20 → убираем один повтор по индексу, чтобы всегда ровно N
    del out[7]
    return out[:count]


